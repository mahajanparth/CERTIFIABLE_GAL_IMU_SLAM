"""Terminal dashboard and PROGRESS.md. Same numbers, two surfaces."""
from __future__ import annotations

from . import evidence as ev
from . import gates
from .ledger import ROOT

BAR_W = 15


def bar(frac: float, width: int = BAR_W) -> str:
    filled = int(round(frac * width))
    return "#" * filled + "." * (width - filled)


def _ms_rows(data, evidence):
    rows = []
    for ms in data["milestones"]:
        done, total = ev.milestone_progress(ms, evidence)
        ok, reasons = gates.evaluate(ms, evidence)
        rows.append((ms, done, total, ok, reasons))
    return rows


def status(data, evidence, verbose: bool = True) -> str:
    out: list[str] = []
    overall = ev.overall_progress(data, evidence)
    title = f"{data.get('project','project')} — Stage {data.get('stage','?')}"
    out.append(f"{title:<48} overall  {bar(overall)}  {overall*100:3.0f}%")
    out.append("")

    for ms, done, total, ok, reasons in _ms_rows(data, evidence):
        gate = "PASS " if ok else "BLOCK"
        if ms["status"] == "not_started" and total == 0:
            gate = "     "
        counts = f"{done}/{total} claims" if total else "no claims yet"
        seed = ms.get("seed") or {}
        seedtxt = ""
        if seed.get("caught") is True:
            seedtxt = "  seed caught"
        elif seed.get("caught") is False:
            seedtxt = "  SEED MISSED"
        out.append(
            f"{ms['id']:<3} {ms['title'][:26]:<27} {ms['branch'][:24]:<25} "
            f"{ms['status'].upper():<13} {counts:<14} gate {gate}{seedtxt}"
        )
        if verbose and not ok and ms["status"] != "not_started":
            for r in reasons[:4]:
                out.append(f"      - {r}")
            if len(reasons) > 4:
                out.append(f"      - ... and {len(reasons)-4} more (orchestrator claims {ms['id']})")

    runs = [(ms, r) for ms in data["milestones"] for r in (ms.get("agent_runs") or [])]
    running = [r for _, r in runs if r["finished"] is None]
    completed = [r for _, r in runs if r["outcome"] == "completed"]
    discarded = [r for _, r in runs if r["outcome"] == "discarded"]
    out.append("")
    out.append(
        f"agents: {len(running)} running · {len(completed)} completed · {len(discarded)} discarded"
    )
    for _, r in [(m, r) for m, r in runs if r["finished"] is None]:
        out.append(f"      running: {r['role']}  {r['agent_id']}  since {r['started']}")
    return "\n".join(out)


def claims_table(ms, evidence) -> str:
    out = [f"{ms['id']} — {ms['title']}   [{ms['status']}]  branch {ms['branch']}", ""]
    claims = ms.get("claims") or []
    if not claims:
        out.append("  (no claims defined yet)")
        return "\n".join(out)
    out.append(f"  {'CLAIM':<10} {'STATUS':<11} {'TEST':<42} STATEMENT")
    for c in claims:
        st = ev.claim_status(c, evidence)
        node = (evidence.get(c["id"]) or {}).get("nodeid", "-")
        if len(node) > 40:
            node = "..." + node[-37:]
        stmt = (c.get("statement") or "")[:60]
        out.append(f"  {c['id']:<10} {st:<11} {node:<42} {stmt}")
    seed = ms.get("seed") or {}
    if seed.get("id"):
        caught = {True: "caught", False: "MISSED", None: "not evaluated"}[seed.get("caught")]
        pub = " (published)" if seed.get("published") else " (withheld)"
        out.append("")
        out.append(f"  seeded defect {seed['id']}: {caught}{pub}")
    return "\n".join(out)


def progress_md(data, evidence) -> str:
    overall = ev.overall_progress(data, evidence)
    lines = [
        f"# Progress — {data.get('project')} (Stage {data.get('stage')})",
        "",
        "Regenerated by `orchestrator report`. **Computed from evidence** — test bindings,",
        "pytest outcomes and independent verifier verdicts — never self-reported.",
        "",
        f"**Overall: {overall*100:.0f}%**",
        "",
        "| M | Title | Branch | Status | Claims | Gate | Seed |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for ms, done, total, ok, _ in _ms_rows(data, evidence):
        counts = f"{done}/{total}" if total else "—"
        gate = "PASS" if ok else "BLOCK"
        seed = ms.get("seed") or {}
        s = {True: "caught", False: "**missed**", None: "—"}[seed.get("caught")]
        lines.append(
            f"| {ms['id']} | {ms['title']} | `{ms['branch']}` | {ms['status']} | {counts} | {gate} | {s} |"
        )
    lines += [
        "",
        "## What the statuses mean",
        "",
        "A claim is `DONE` only when **all five** signals are green: a test carries",
        "`@pytest.mark.claim` for it, that test passes when pytest is actually run, an",
        "independent verifier returned `CONFIRMED`, that verifier caught its milestone's",
        "seeded defect, and the branch is merged. Anything else blocks the gate.",
        "",
        "| Status | Meaning |",
        "| --- | --- |",
        "| `UNTESTED` | no test carries `@pytest.mark.claim` for this id |",
        "| `FAILING` | a test exists and it fails |",
        "| `UNVERIFIED` | the test passes but no independent `CONFIRMED` verdict exists |",
        "| `UNTESTABLE` | a verifier could not construct a test for it |",
        "| `REFUTED` | a verifier actively broke it |",
        "| `DONE` | all five signals green |",
    ]
    return "\n".join(lines) + "\n"


def write_progress_md(data, evidence) -> str:
    p = ROOT / "PROGRESS.md"
    p.write_text(progress_md(data, evidence))
    return str(p)
